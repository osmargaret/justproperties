            <h2 id="lekki" class="font-bold font-serif text-gray-900 mb-4 text-3xl">2. Lekki Phase 1: Prime Location Performance</h2>
            <p class="text-gray-500 mb-4 leading-loose">
              Lekki Phase 1 remains the most sought-after residential area in Lagos, with average duplex prices 
              now ranging from ₦85 million to ₦250 million.
            </p>

            <h3 class="font-bold text-gray-900 mb-3 text-2xl">Recent Developments in Lekki Phase 1</h3>
            <ul class="list-disc list-inside text-gray-500 mb-6 space-y-2 leading-loose">
              <li>Completion of road rehabilitation on Admiralty Way</li>
              <li>New international schools opening in the vicinity</li>
              <li>Expansion of retail and entertainment options</li>
              <li>Improved security infrastructure with additional police posts</li>
            </ul>

            <h2 id="ikorodu" class="font-bold font-serif text-gray-900 mb-4 text-3xl">3. Ikorodu: The Emerging Investment Hotspot</h2>
            <p class="text-gray-500 mb-6 leading-loose">
              Ikorodu has emerged as one of the most promising investment locations in Lagos, offering affordable 
              entry points with significant appreciation potential.
            </p>

            <div class="bg-green-50 border-l-4 border-emerald-600 p-6 rounded-lg mb-8">
              <h4 class="text-emerald-600 font-semibold mb-2">Investment Highlight</h4>
              <p class="text-gray-500 leading-relaxed">Properties in Ikorodu have appreciated by an average of 22% over the past two years.</p>
            </div>

            <h2 id="prices" class="font-bold font-serif text-gray-900 mb-4 text-3xl">4. Price Trends by Area</h2>
            <ul class="list-disc list-inside text-gray-500 mb-6 space-y-2 leading-loose">
              <li><strong>Lekki Phase 1:</strong> 4-bed duplex: ₦85-120M | 5-bed duplex: ₦120-250M</li>
              <li><strong>Ikoyi:</strong> 4-bed duplex: ₦150-300M | 5-bed duplex: ₦250-500M</li>
              <li><strong>Victoria Island:</strong> 3-bed apartment: ₦80-150M | 4-bed duplex: ₦180-350M</li>
              <li><strong>Ajah:</strong> 4-bed duplex: ₦45-80M | 5-bed duplex: ₦70-120M</li>
              <li><strong>Ikorodu:</strong> 4-bed duplex: ₦35-60M | 5-bed duplex: ₦55-90M</li>
              <li><strong>Ikeja GRA:</strong> 4-bed duplex: ₦95-180M | 5-bed duplex: ₦150-280M</li>
            </ul>

            <h2 id="investment" class="font-bold font-serif text-gray-900 mb-4 text-3xl">5. Investment Opportunities 2025</h2>
            <p class="text-gray-500 mb-4 leading-loose">Based on current trends and upcoming developments, we've identified several promising investment opportunities for 2025:</p>

            <h3 class="font-bold text-gray-900 mb-3 text-2xl">Short-term Rentals (Short-Let)</h3>
            <p class="text-gray-500 mb-6 leading-loose">With the rebound in business travel and tourism, short-let apartments in Victoria Island, Ikoyi, and Lekki are generating excellent returns.</p>

            <h3 class="font-bold text-gray-900 mb-3 text-2xl">Land Banking in Developing Areas</h3>
            <p class="text-gray-500 mb-6 leading-loose">Areas along the Lekki-Epe corridor offer excellent land banking opportunities. Land prices have increased by 30-50% annually.</p>

            <h2 id="forecast" class="font-bold font-serif text-gray-900 mb-4 text-3xl">6. 2025-2026 Market Forecast</h2>
            <p class="text-gray-500 mb-6 leading-loose">
