          </div>

          <div class="highlight-box">
            <h4>Key Insight</h4>
            <p>The eastern axis (Lekki, Ajah, Ibeju-Lekki) continues to outperform other areas, with price 
            appreciation rates 5-7% higher than the Lagos average. This trend is expected to continue through 
            2026 as infrastructure development accelerates.</p>
          </div>

          <h2 id="lekki">2. Lekki Phase 1: Prime Location Performance</h2>
          <p>
            Lekki Phase 1 remains the most sought-after residential area in Lagos, with average duplex prices 
            now ranging from ₦85 million to ₦250 million depending on location and specifications. The area has 
            seen a 12% increase in property values over the past 12 months, driven by limited land availability 
            and high demand from corporate executives and diaspora investors.
          </p>

          <h3>Recent Developments in Lekki Phase 1</h3>
          <ul>
            <li>Completion of road rehabilitation on Admiralty Way and surrounding streets</li>
            <li>New international schools opening in the vicinity</li>
            <li>Expansion of retail and entertainment options</li>
            <li>Improved security infrastructure with additional police posts</li>
          </ul>

          <h2 id="ikorodu">3. Ikorodu: The Emerging Investment Hotspot</h2>
          <p>
            Ikorodu has emerged as one of the most promising investment locations in Lagos, offering affordable 
            entry points with significant appreciation potential. Property prices in prime Ikorodu locations 
            (Gbaga, Agric, Isawo) range from ₦15 million for 3-bedroom bungalows to ₦45 million for luxury 
            detached duplexes.
          </p>

          <div class="highlight-box">
            <h4>Investment Highlight</h4>
            <p>Properties in Ikorodu have appreciated by an average of 22% over the past two years, outperforming 
            many traditional hotspots. With the proposed Ikorodu-Epe coastal road and expanded ferry services, 
            connectivity improvements are expected to drive further growth.</p>
          </div>

          <h2 id="prices">4. Price Trends by Area</h2>
          <p>
            Understanding price variations across different Lagos neighborhoods is crucial for making informed 
            investment decisions. Below is a breakdown of average property prices in key locations:
          </p>

          <ul>
            <li><strong>Lekki Phase 1:</strong> 4-bed duplex: ₦85-120M | 5-bed duplex: ₦120-250M</li>
            <li><strong>Ikoyi:</strong> 4-bed duplex: ₦150-300M | 5-bed duplex: ₦250-500M</li>
            <li><strong>Victoria Island:</strong> 3-bed apartment: ₦80-150M | 4-bed duplex: ₦180-350M</li>
            <li><strong>Ajah:</strong> 4-bed duplex: ₦45-80M | 5-bed duplex: ₦70-120M</li>
            <li><strong>Ikorodu:</strong> 4-bed duplex: ₦35-60M | 5-bed duplex: ₦55-90M</li>
            <li><strong>Ikeja GRA:</strong> 4-bed duplex: ₦95-180M | 5-bed duplex: ₦150-280M</li>
          </ul>

          <h2 id="investment">5. Investment Opportunities 2025</h2>
          <p>
            Based on current trends and upcoming developments, we've identified several promising investment 
            opportunities for 2025:
          </p>

          <h3>Short-term Rentals (Short-Let)</h3>
          <p>
            With the rebound in business travel and tourism, short-let apartments in Victoria Island, Ikoyi, 
            and Lekki are generating excellent returns. Investors can expect monthly returns of 15-25% on 
            well-managed short-let properties.
          </p>

          <h3>Land Banking in Developing Areas</h3>
          <p>
            Areas along the Lekki-Epe corridor, particularly around the new airport and seaport, offer excellent 
            land banking opportunities. Land prices in these areas have increased by 30-50% annually over the 
            past three years.
          </p>

          <h3>Uncompleted Property Completion</h3>
          <p>
            Purchasing and completing uncompleted properties in established neighborhoods continues to offer 
            attractive profit margins, typically 20-35% upon completion and sale.
          </p>

          <h2 id="forecast">6. 2025-2026 Market Forecast</h2>
          <p>
            Looking ahead, we project continued growth in the Lagos real estate market, albeit at a moderated 
            pace compared to the post-pandemic boom. Key factors influencing the market include:
          </p>

          <ul>
            <li>Interest rate stability and improved mortgage accessibility</li>
            <li>Completion of major infrastructure projects</li>
            <li>Continued diaspora investment inflows</li>
            <li>Population growth and urbanization trends</li>
          </ul>

          <p>
            Our forecast suggests overall price appreciation of 10-12% for 2025, with emerging areas like 
            Ikorodu and parts of Ibeju-Lekki potentially seeing 15-20% growth.
          </p>
